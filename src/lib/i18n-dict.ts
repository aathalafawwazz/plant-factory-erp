/**
 * Pure translator — safe on both server and client. For client components
 * prefer `useLang().t()` (from `./i18n`) so re-renders track the active lang.
 */
export function translate(key: string, lang: Lang): string {
  return dict[key]?.[lang] ?? key;
}

// Internal: the provider & hook read the same dict via this getter so client
// and server stay in sync without bundling duplicates.
export function getDictEntry(key: string): Record<Lang, string> | undefined {
  return dict[key];
}
